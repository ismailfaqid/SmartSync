import jsPDF from 'jspdf'

/**
 * Formats notes into a beautiful WhatsApp-ready message string
 */
export function formatNotesForWhatsApp(session, notes) {
  if (!session || !notes || notes.length === 0) {
    return 'No notes recorded yet in this seminar session.'
  }

  const lines = []

  // Header
  lines.push(`🎙️ *${session.title.toUpperCase()}*`)
  lines.push(`👤 *Speaker:* ${session.speaker_name}${session.speaker_role ? ` (${session.speaker_role})` : ''}`)
  if (session.sponsor_name) {
    lines.push(`💎 *Sponsor:* ${session.sponsor_name}`)
  }
  lines.push(`📅 *Date:* ${new Date().toLocaleDateString('en-US', { month: 'short', day: 'numeric', year: 'numeric' })}`)
  lines.push(`━━━━━━━━━━━━━━━━━━━━━`)
  lines.push('')

  // Body
  notes.forEach((note, idx) => {
    lines.push(`📌 *${idx + 1}. ${note.heading}* [${note.timestamp_marker || 'Live'}]`)
    if (Array.isArray(note.bullet_points)) {
      note.bullet_points.forEach((bullet) => {
        lines.push(`  • ${bullet}`)
      })
    }
    lines.push('')
  })

  // Footer
  lines.push(`━━━━━━━━━━━━━━━━━━━━━`)
  lines.push(`⚡ *Generated in real-time via SmartSync*`)
  lines.push(`🔗 Access live session: ${window.location.origin}/#${session.short_code}`)

  return lines.join('\n')
}

/**
 * Triggers WhatsApp direct link with encoded text
 */
export function shareViaWhatsApp(session, notes) {
  const formattedText = formatNotesForWhatsApp(session, notes)
  const encoded = encodeURIComponent(formattedText)
  const url = `https://wa.me/?text=${encoded}`
  window.open(url, '_blank', 'noopener,noreferrer')
}

/**
 * Copies formatted markdown to clipboard
 */
export async function copyMarkdownToClipboard(session, notes) {
  if (!notes || notes.length === 0) return false

  let md = `# ${session.title}\n\n`
  md += `**Speaker:** ${session.speaker_name}\n`
  if (session.sponsor_name) md += `**Sponsor:** ${session.sponsor_name}\n`
  md += `**Live Date:** ${new Date().toLocaleString()}\n\n---\n\n`

  notes.forEach((note, idx) => {
    md += `### ${idx + 1}. ${note.heading} (${note.timestamp_marker || 'Live'})\n\n`
    if (Array.isArray(note.bullet_points)) {
      note.bullet_points.forEach((bullet) => {
        md += `- ${bullet}\n`
      })
    }
    md += '\n'
  })

  md += `---\n*Generated by SmartSync AI Seminar Platform*\n`

  try {
    await navigator.clipboard.writeText(md)
    return true
  } catch (err) {
    console.error('Failed to copy to clipboard:', err)
    return false
  }
}

/**
 * Shares via native Web Share API on mobile devices
 */
export async function shareViaWebShare(session, notes) {
  if (navigator.share) {
    try {
      await navigator.share({
        title: session.title,
        text: `Live Seminar Notes: ${session.title} by ${session.speaker_name}\n\nKey takeaways recorded via SmartSync.`,
        url: `${window.location.origin}/#${session.short_code}`,
      })
      return true
    } catch (err) {
      if (err.name !== 'AbortError') {
        console.error('Web share error:', err)
      }
    }
  }
  return false
}

/**
 * Generates and downloads a clean, professional PDF document using jsPDF
 */
export function generateNotesPDF(session, notes) {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4',
  })

  const pageWidth = doc.internal.pageSize.getWidth()
  const pageHeight = doc.internal.pageSize.getHeight()
  const margin = 18
  const contentWidth = pageWidth - margin * 2
  let y = margin

  // Page Header Bar
  doc.setFillColor(15, 23, 42) // Dark Navy slate
  doc.rect(0, 0, pageWidth, 28, 'F')

  // Accent Line
  doc.setFillColor(16, 185, 129) // Emerald
  doc.rect(0, 27, pageWidth, 1.5, 'F')

  // Brand Name
  doc.setFont('helvetica', 'bold')
  doc.setFontSize(14)
  doc.setTextColor(16, 185, 129)
  doc.text('SmartSync', margin, 12)

  doc.setFont('helvetica', 'normal')
  doc.setFontSize(9)
  doc.setTextColor(148, 163, 184)
  doc.text('AI Seminar Live Documentation', margin, 18)

  // Session Code Badge on top right
  doc.setFontSize(9)
  doc.setTextColor(241, 245, 249)
  doc.text(`CODE: ${session.short_code.toUpperCase()}`, pageWidth - margin, 14, { align: 'right' })

  y = 38

  // Seminar Title
  doc.setFont('helvetica', 'bold')
  doc.setFontSize(16)
  doc.setTextColor(15, 23, 42)
  const titleLines = doc.splitTextToSize(session.title, contentWidth)
  doc.text(titleLines, margin, y)
  y += titleLines.length * 7 + 4

  // Metadata Box
  doc.setFillColor(248, 250, 252)
  doc.setDrawColor(226, 232, 240)
  doc.roundedRect(margin, y, contentWidth, 22, 3, 3, 'FD')

  doc.setFont('helvetica', 'normal')
  doc.setFontSize(9)
  doc.setTextColor(71, 85, 105)
  doc.text(`Speaker:`, margin + 4, y + 7)
  doc.setFont('helvetica', 'bold')
  doc.setTextColor(15, 23, 42)
  doc.text(`${session.speaker_name}`, margin + 20, y + 7)

  if (session.sponsor_name) {
    doc.setFont('helvetica', 'normal')
    doc.setTextColor(71, 85, 105)
    doc.text(`Sponsored by:`, margin + 4, y + 14)
    doc.setFont('helvetica', 'bold')
    doc.setTextColor(5, 150, 105)
    doc.text(`${session.sponsor_name}`, margin + 28, y + 14)
  }

  doc.setFont('helvetica', 'normal')
  doc.setTextColor(100, 116, 139)
  doc.text(`Generated: ${new Date().toLocaleDateString()} ${new Date().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' })}`, pageWidth - margin - 4, y + 7, { align: 'right' })
  doc.text(`Total Sections: ${notes.length}`, pageWidth - margin - 4, y + 14, { align: 'right' })

  y += 30

  // Notes Sections
  notes.forEach((note, index) => {
    // Check if new page is needed
    if (y > pageHeight - 40) {
      doc.addPage()
      y = margin
    }

    // Section Pill / Heading Number
    doc.setFillColor(241, 245, 249)
    doc.roundedRect(margin, y, contentWidth, 8, 2, 2, 'F')

    doc.setFont('helvetica', 'bold')
    doc.setFontSize(11)
    doc.setTextColor(15, 23, 42)
    doc.text(`${index + 1}. ${note.heading}`, margin + 4, y + 5.5)

    if (note.timestamp_marker) {
      doc.setFont('helvetica', 'normal')
      doc.setFontSize(8.5)
      doc.setTextColor(100, 116, 139)
      doc.text(note.timestamp_marker, pageWidth - margin - 4, y + 5.5, { align: 'right' })
    }

    y += 13

    // Bullet Points
    if (Array.isArray(note.bullet_points)) {
      note.bullet_points.forEach((bullet) => {
        const bulletLines = doc.splitTextToSize(bullet, contentWidth - 8)
        
        // Page break check inside bullets
        if (y + bulletLines.length * 5 > pageHeight - 20) {
          doc.addPage()
          y = margin
        }

        // Emerald bullet dot
        doc.setFillColor(16, 185, 129)
        doc.circle(margin + 3, y - 1, 1, 'F')

        doc.setFont('helvetica', 'normal')
        doc.setFontSize(9.5)
        doc.setTextColor(51, 65, 85)
        doc.text(bulletLines, margin + 8, y)
        y += bulletLines.length * 5 + 3
      })
    }

    y += 4
  })

  // Footer on all pages
  const totalPages = doc.internal.getNumberOfPages()
  for (let i = 1; i <= totalPages; i++) {
    doc.setPage(i)
    doc.setFont('helvetica', 'normal')
    doc.setFontSize(8)
    doc.setTextColor(148, 163, 184)
    doc.text(
      `SmartSync Platform · Session ${session.short_code} · Page ${i} of ${totalPages}`,
      pageWidth / 2,
      pageHeight - 8,
      { align: 'center' }
    )
  }

  // Save PDF
  const filename = `${session.short_code}-smartsync-notes.pdf`
  doc.save(filename)
}
